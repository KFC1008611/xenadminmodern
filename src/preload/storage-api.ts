import {
  isoDeleteContract,
  isoListAllContract,
  isoListContract,
  pbdCreateContract,
  pbdDestroyContract,
  pbdListContract,
  pbdPlugContract,
  pbdUnplugContract,
  srCreateContract,
  srDestroyContract,
  srDetachContract,
  srForgetContract,
  srGetThinStatsContract,
  srIntroduceContract,
  srListContract,
  srProbeIscsiContract,
  srProbeNfsContract,
  srScanContract,
  srSetDefaultContract,
  srSetSharedContract,
  srUpdateIdentityContract,
  vdiAddTagContract,
  vdiAttachExistingContract,
  vdiCloneContract,
  vdiCopyContract,
  vdiCreateContract,
  vdiCreateForVmContract,
  vdiDestroyContract,
  vdiGetAllowedOperationsContract,
  vdiListAttachableContract,
  vdiListContract,
  vdiMoveContract,
  vdiRemoveTagContract,
  vdiResizeContract,
  vdiSetNameDescriptionContract,
  vdiSetNameLabelContract,
  vdiSnapshotContract,
} from '../shared/ipc-contracts/storage'
import {
  createIpcContractInvoker,
  type IpcInvokeTransport,
} from './ipc-contract-client'

export function createStorageApi(transport: IpcInvokeTransport) {
  return {
    storage: {
      listSrs: createIpcContractInvoker(srListContract, transport),
      listVdis: createIpcContractInvoker(vdiListContract, transport),
      createVdi: createIpcContractInvoker(vdiCreateContract, transport),
      destroyVdi: createIpcContractInvoker(vdiDestroyContract, transport),
      resizeVdi: createIpcContractInvoker(vdiResizeContract, transport),
      createForVm: createIpcContractInvoker(vdiCreateForVmContract, transport),
      getAllowedOperations: createIpcContractInvoker(
        vdiGetAllowedOperationsContract,
        transport,
      ),
      listAttachableVdis: createIpcContractInvoker(vdiListAttachableContract, transport),
      attachExistingVdi: createIpcContractInvoker(vdiAttachExistingContract, transport),
      moveVdi: createIpcContractInvoker(vdiMoveContract, transport),
      cloneVdi: createIpcContractInvoker(vdiCloneContract, transport),
      snapshotVdi: createIpcContractInvoker(vdiSnapshotContract, transport),
      copyVdi: createIpcContractInvoker(vdiCopyContract, transport),
      setVdiNameLabel: createIpcContractInvoker(vdiSetNameLabelContract, transport),
      setVdiNameDescription: createIpcContractInvoker(
        vdiSetNameDescriptionContract,
        transport,
      ),
      addVdiTag: createIpcContractInvoker(vdiAddTagContract, transport),
      removeVdiTag: createIpcContractInvoker(vdiRemoveTagContract, transport),
    },
    sr: {
      create: createIpcContractInvoker(srCreateContract, transport),
      destroy: createIpcContractInvoker(srDestroyContract, transport),
      scan: createIpcContractInvoker(srScanContract, transport),
      detach: createIpcContractInvoker(srDetachContract, transport),
      setDefault: createIpcContractInvoker(srSetDefaultContract, transport),
      probeNfs: createIpcContractInvoker(srProbeNfsContract, transport),
      probeIscsi: createIpcContractInvoker(srProbeIscsiContract, transport),
      introduce: createIpcContractInvoker(srIntroduceContract, transport),
      forget: createIpcContractInvoker(srForgetContract, transport),
      setShared: createIpcContractInvoker(srSetSharedContract, transport),
      getThinStats: createIpcContractInvoker(srGetThinStatsContract, transport),
      updateIdentity: createIpcContractInvoker(srUpdateIdentityContract, transport),
    },
    pbd: {
      list: createIpcContractInvoker(pbdListContract, transport),
      create: createIpcContractInvoker(pbdCreateContract, transport),
      plug: createIpcContractInvoker(pbdPlugContract, transport),
      unplug: createIpcContractInvoker(pbdUnplugContract, transport),
      destroy: createIpcContractInvoker(pbdDestroyContract, transport),
    },
    iso: {
      list: createIpcContractInvoker(isoListContract, transport),
      listAll: createIpcContractInvoker(isoListAllContract, transport),
      delete: createIpcContractInvoker(isoDeleteContract, transport),
    },
  }
}
