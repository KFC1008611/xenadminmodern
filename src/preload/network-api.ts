import {
  bondCreateContract,
  bondDestroyContract,
  bondDestroyGroupContract,
  bondGetRecordContract,
  bondListContract,
  networkAddTagContract,
  networkCreateContract,
  networkDestroyContract,
  networkGetAllowedOpsContract,
  networkListContract,
  networkRemoveTagContract,
  networkRenameContract,
  networkUpdateOtherConfigContract,
  pifGetForHostContract,
  pifListContract,
  pifReconfigureIpContract,
  pifScanContract,
  tunnelCreateContract,
  tunnelDestroyContract,
  tunnelListContract,
  vifClearQosContract,
  vifCreateContract,
  vifDestroyContract,
  vifPlugContract,
  vifSetQosContract,
  vifUnplugContract,
  vifMoveContract,
  vlanCreateContract,
  vlanDestroyContract,
  vlanDestroyNetworkContract,
  vlanGetRecordContract,
  vlanListContract,
} from '../shared/ipc-contracts/network'
import {
  createIpcContractInvoker,
  type IpcInvokeTransport,
} from './ipc-contract-client'

export function createNetworkApi(transport: IpcInvokeTransport) {
  return {
    network: {
      list: createIpcContractInvoker(networkListContract, transport),
      listPifs: createIpcContractInvoker(pifListContract, transport),
      create: createIpcContractInvoker(networkCreateContract, transport),
      destroy: createIpcContractInvoker(networkDestroyContract, transport),
      rename: createIpcContractInvoker(networkRenameContract, transport),
      getAllowedOps: createIpcContractInvoker(networkGetAllowedOpsContract, transport),
      addTag: createIpcContractInvoker(networkAddTagContract, transport),
      removeTag: createIpcContractInvoker(networkRemoveTagContract, transport),
      updateOtherConfig: createIpcContractInvoker(
        networkUpdateOtherConfigContract,
        transport,
      ),
    },
    pif: {
      reconfigureIp: createIpcContractInvoker(pifReconfigureIpContract, transport),
      scan: createIpcContractInvoker(pifScanContract, transport),
      getForHost: createIpcContractInvoker(pifGetForHostContract, transport),
    },
    vif: {
      create: createIpcContractInvoker(vifCreateContract, transport),
      destroy: createIpcContractInvoker(vifDestroyContract, transport),
      plug: createIpcContractInvoker(vifPlugContract, transport),
      unplug: createIpcContractInvoker(vifUnplugContract, transport),
      move: createIpcContractInvoker(vifMoveContract, transport),
      setQos: createIpcContractInvoker(vifSetQosContract, transport),
      clearQos: createIpcContractInvoker(vifClearQosContract, transport),
    },
    bond: {
      list: createIpcContractInvoker(bondListContract, transport),
      create: createIpcContractInvoker(bondCreateContract, transport),
      destroy: createIpcContractInvoker(bondDestroyContract, transport),
      destroyGroup: createIpcContractInvoker(bondDestroyGroupContract, transport),
      getRecord: createIpcContractInvoker(bondGetRecordContract, transport),
    },
    vlan: {
      list: createIpcContractInvoker(vlanListContract, transport),
      create: createIpcContractInvoker(vlanCreateContract, transport),
      destroy: createIpcContractInvoker(vlanDestroyContract, transport),
      destroyNetwork: createIpcContractInvoker(vlanDestroyNetworkContract, transport),
      getRecord: createIpcContractInvoker(vlanGetRecordContract, transport),
    },
    tunnel: {
      list: createIpcContractInvoker(tunnelListContract, transport),
      create: createIpcContractInvoker(tunnelCreateContract, transport),
      destroy: createIpcContractInvoker(tunnelDestroyContract, transport),
    },
  }
}
