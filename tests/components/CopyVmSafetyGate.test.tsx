import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { CopyVmDialog } from '../../src/renderer/src/components/vm/CopyVmDialog'
import { CloneTemplateDialog } from '../../src/renderer/src/components/template/CloneTemplateDialog'
import { useConnectionManagerStore } from '../../src/renderer/src/store/connectionManager.store'
import { useCopyStore } from '../../src/renderer/src/store/copy.store'
import { copyOperation, copyPlan } from '../helpers/vm-copy-fixtures'
import type { VmCopyPlan } from '../../src/shared/types/xapi'
const vm = { ref: 'OpaqueRef:vm', name_label: 'Source', connectionId: 'pool-1' }
function deferred<T>() {
  let resolve!: (v: T) => void, reject!: (error: Error) => void
  const promise = new Promise<T>((res, rej) => { resolve = res; reject = rej })
  return { resolve, reject, promise }
}
beforeEach(() => {
  useConnectionManagerStore.setState({ connections: [{ id: 'pool-1', state: 'connected', poolName: 'Source Pool' }, { id: 'pool-2', state: 'connected', poolName: 'Target Pool' }] as any })
  useCopyStore.setState({ operations: [] })
  Object.assign(window.xapi, { vm: { copyPlan: vi.fn().mockResolvedValue(copyPlan), copy: vi.fn().mockResolvedValue(copyOperation), copyOperations: vi.fn().mockResolvedValue([]) } })
})
describe('copy preflight and submission', () => {
  it('submits a keyboard form once and exposes an accepted background operation', async () => {
    const close = vi.fn(); render(<CopyVmDialog open vm={vm} onClose={close} />)
    const submit = await screen.findByRole('button', { name: '开始复制' })
    await waitFor(() => expect(submit).toBeEnabled())
    const input = screen.getByLabelText('新VM名称')
    fireEvent.change(input, { target: { value: 'New copy' } })
    fireEvent.submit(input.closest('form')!); fireEvent.submit(input.closest('form')!)
    await waitFor(() => expect(close).toHaveBeenCalledOnce())
    expect(window.xapi.vm.copy).toHaveBeenCalledOnce()
    expect(window.xapi.vm.copy).toHaveBeenCalledWith('pool-1', expect.objectContaining({ newName: 'New copy', mode: 'clone' }))
    expect(useCopyStore.getState().operations[0].id).toBe(copyOperation.id)
    expect(screen.getByRole('button', { name: '关闭复制窗口' })).toHaveAccessibleName()
  })
  it('never applies an old pool response after target selection changes', async () => {
    const old = deferred<VmCopyPlan>()
    vi.mocked(window.xapi.vm.copyPlan).mockImplementation((_s, _v, target) => target === 'pool-1' ? old.promise : Promise.resolve({ ...copyPlan, targetConnectionId: 'pool-2', allowedModes: ['cross-pool-copy'] }))
    render(<CopyVmDialog open vm={vm} onClose={vi.fn()} />)
    fireEvent.change(screen.getByLabelText('目标资源池'), { target: { value: 'pool-2' } })
    await screen.findByLabelText('目标主机')
    await act(async () => old.resolve(copyPlan))
    expect(screen.getByLabelText('目标资源池')).toHaveValue('pool-2')
    expect(screen.getByLabelText('目标主机')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '开始复制' })).toBeDisabled()
  })
  it('clears stale resources and blocks submission when reading a new pool fails', async () => {
    vi.mocked(window.xapi.vm.copyPlan).mockImplementation((_s, _v, target) => target === 'pool-1' ? Promise.resolve(copyPlan) : Promise.reject(new Error('offline')))
    render(<CopyVmDialog open vm={vm} onClose={vi.fn()} />)
    fireEvent.click(await screen.findByRole('radio', { name: '完整复制' }))
    fireEvent.change(screen.getByLabelText('目标 SR'), { target: { value: 'OpaqueRef:sr' } })
    fireEvent.change(screen.getByLabelText('目标资源池'), { target: { value: 'pool-2' } })
    expect(await screen.findByRole('alert')).toHaveTextContent('offline')
    expect(screen.queryByRole('option', { name: /Storage/ })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '开始复制' })).toBeDisabled()
  })
  it('keeps names, copy mode and target storage separate for templates', async () => {
    render(<CloneTemplateDialog open template={vm} onClose={vi.fn()} onSuccess={vi.fn()} />)
    expect(await screen.findByRole('dialog')).toHaveAccessibleName('复制模板')
    expect(screen.getByLabelText('新模板名称')).toHaveValue('Copy of Source')
    fireEvent.click(await screen.findByRole('radio', { name: '完整复制' }))
    expect(screen.getByLabelText('目标 SR')).toHaveValue('')
    expect(screen.getByRole('button', { name: '开始复制' })).toBeDisabled()
  })
  it('requires explicit network, storage and transfer choices for cross-pool copies', async () => {
    const disk = { vdiRef: 'OpaqueRef:disk', vbdRef: 'OpaqueRef:vbd', vmRef: vm.ref, vmName: 'History', history: true, suspend: true, device: '', name: 'Suspend image', size: 100, srRef: 'OpaqueRef:source-sr' }
    const vif = { vifRef: 'OpaqueRef:vif', vmRef: vm.ref, vmName: 'History', history: true, device: '2', networkRef: 'OpaqueRef:source-net', networkName: 'Business' }
    vi.mocked(window.xapi.vm.copyPlan).mockResolvedValue({ ...copyPlan, targetConnectionId: 'pool-2', allowedModes: ['cross-pool-copy'], disks: [disk], vifs: [vif] })
    render(<CopyVmDialog open vm={vm} initialTargetConnectionId="pool-2" onClose={vi.fn()} />)
    const host = await screen.findByLabelText('目标主机')
    expect(screen.getByText(/不保留快照历史/)).toBeInTheDocument()
    expect(host).toHaveValue('')
    fireEvent.change(host, { target: { value: 'OpaqueRef:host' } })
    const selects = screen.getAllByRole('combobox')
    expect(selects.slice(-2).every((s) => (s as HTMLSelectElement).value === '')).toBe(true)
    fireEvent.change(screen.getByLabelText('传输网络'), { target: { value: 'OpaqueRef:net' } })
    fireEvent.change(screen.getByLabelText(/Suspend image/), { target: { value: 'OpaqueRef:sr' } })
    fireEvent.change(screen.getByLabelText(/网卡 2/), { target: { value: 'OpaqueRef:net' } })
    expect(screen.getByRole('button', { name: '开始复制' })).toBeEnabled()
    fireEvent.change(host, { target: { value: '' } })
    expect(screen.getByRole('button', { name: '开始复制' })).toBeDisabled()
  })
  it('shows a stopped-source requirement without submitting a running VM', async () => {
    vi.mocked(window.xapi.vm.copyPlan).mockResolvedValue({ ...copyPlan, allowedModes: [], blockers: ['请先正常关闭源虚拟机'] })
    render(<CopyVmDialog open vm={vm} onClose={vi.fn()} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('正常关闭')
    expect(screen.getByRole('button', { name: '开始复制' })).toBeDisabled()
    expect(window.xapi.vm.copy).not.toHaveBeenCalled()
  })
  it('shows the mounted-ISO blocker without same-pool controls and resumes after explicit preflight', async () => {
    vi.mocked(window.xapi.vm.copyPlan)
      .mockResolvedValueOnce({ ...copyPlan, targetConnectionId: 'pool-2', allowedModes: [], blockers: ['源光驱 3 已挂载 ISO；请先手动弹出并重新读取预检'] })
      .mockResolvedValue({ ...copyPlan, targetConnectionId: 'pool-2', allowedModes: ['cross-pool-copy'] })
    render(<CopyVmDialog open vm={vm} initialTargetConnectionId="pool-2" onClose={vi.fn()} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('手动弹出')
    expect(screen.getByRole('button', { name: '开始复制' })).toBeDisabled()
    expect(screen.queryByRole('radio', { name: '快速克隆' })).not.toBeInTheDocument()
    expect(screen.queryByLabelText('目标 SR')).not.toBeInTheDocument()
    expect(window.xapi.vm.copy).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: '重新读取预检' }))
    expect(await screen.findByLabelText('目标主机')).toBeInTheDocument()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  })
  it('retrieves durable history if the start acknowledgement is lost', async () => {
    vi.mocked(window.xapi.vm.copy).mockRejectedValue(new Error('IPC transport lost'))
    vi.mocked(window.xapi.vm.copyOperations).mockResolvedValue([copyOperation])
    render(<CopyVmDialog open vm={vm} onClose={vi.fn()} />)
    const submit = screen.getByRole('button', { name: '开始复制' }); await waitFor(() => expect(submit).toBeEnabled())
    fireEvent.click(submit)
    await waitFor(() => expect(useCopyStore.getState().operations[0]?.id).toBe(copyOperation.id))
    expect(window.xapi.vm.copy).toHaveBeenCalledOnce()
  })
  it.each(['accepted', 'rejected'])('unlocks the current dialog after a source reconnect and an %s response', async (outcome) => {
    const pending = deferred<typeof copyOperation>()
    vi.mocked(window.xapi.vm.copy).mockReturnValue(pending.promise)
    const close = vi.fn(); render(<CopyVmDialog open vm={vm} onClose={close} />)
    const submit = screen.getByRole('button', { name: '开始复制' })
    await waitFor(() => expect(submit).toBeEnabled())
    fireEvent.click(submit)
    await act(async () => {
      useConnectionManagerStore.setState((s) => ({ connections: s.connections.map((c) => c.id === vm.connectionId ? { ...c, epoch: (c.epoch ?? 0) + 1 } : c) }))
    })
    await waitFor(() => expect(window.xapi.vm.copyPlan).toHaveBeenCalledTimes(2))
    expect(submit).toBeDisabled()
    await act(async () => {
      if (outcome === 'accepted') pending.resolve(copyOperation)
      else pending.reject(new Error('acknowledgement lost'))
    })
    expect(close).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: '关闭复制窗口' })).toBeEnabled()
    expect(screen.getByRole('button', { name: '取消' })).toBeEnabled()
    expect(screen.getByRole('button', { name: '重新读取预检' })).toBeEnabled()
    expect(submit).toBeEnabled()
    expect(window.xapi.vm.copy).toHaveBeenCalledOnce()
    if (outcome === 'accepted') expect(useCopyStore.getState().operations[0]?.id).toBe(copyOperation.id)
    else expect(window.xapi.vm.copyOperations).toHaveBeenCalledOnce()
  })
  it('preserves the placement and closes on acceptance when an unrelated pool reconnects', async () => {
    const pending = deferred<typeof copyOperation>()
    vi.mocked(window.xapi.vm.copy).mockReturnValue(pending.promise)
    const close = vi.fn(); render(<CopyVmDialog open vm={vm} onClose={close} />)
    fireEvent.click(await screen.findByRole('radio', { name: '完整复制' }))
    const sr = screen.getByLabelText('目标 SR')
    fireEvent.change(sr, { target: { value: 'OpaqueRef:sr' } })
    fireEvent.click(screen.getByRole('button', { name: '开始复制' }))
    await act(async () => {
      useConnectionManagerStore.setState((s) => ({ connections: s.connections.map((c) => c.id === 'pool-2' ? { ...c, epoch: (c.epoch ?? 0) + 1 } : c) }))
    })
    expect(window.xapi.vm.copyPlan).toHaveBeenCalledOnce()
    expect(sr).toHaveValue('OpaqueRef:sr')
    await act(async () => pending.resolve(copyOperation))
    expect(close).toHaveBeenCalledOnce()
    expect(useCopyStore.getState().operations[0]?.id).toBe(copyOperation.id)
  })
  it.each(['accepted', 'rejected'])('ignores an old %s response while a reopened dialog submits a new request', async (outcome) => {
    const old = deferred<typeof copyOperation>(), current = deferred<typeof copyOperation>()
    vi.mocked(window.xapi.vm.copy).mockReturnValueOnce(old.promise).mockReturnValueOnce(current.promise)
    const close = vi.fn()
    const { rerender } = render(<CopyVmDialog open vm={vm} onClose={close} />)
    const firstSubmit = screen.getByRole('button', { name: '开始复制' })
    await waitFor(() => expect(firstSubmit).toBeEnabled())
    fireEvent.click(firstSubmit)
    rerender(<CopyVmDialog open={false} vm={vm} onClose={close} />)
    rerender(<CopyVmDialog open vm={vm} onClose={close} />)
    const submit = screen.getByRole('button', { name: '开始复制' })
    await waitFor(() => expect(submit).toBeEnabled())
    fireEvent.click(submit)
    expect(window.xapi.vm.copy).toHaveBeenCalledTimes(2)
    await act(async () => {
      if (outcome === 'accepted') old.resolve(copyOperation)
      else old.reject(new Error('old acknowledgement lost'))
    })
    expect(close).not.toHaveBeenCalled()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(submit).toBeDisabled()
    expect(screen.getByRole('button', { name: '关闭复制窗口' })).toBeDisabled()
    await act(async () => current.resolve({ ...copyOperation, id: 'copy-2' }))
    expect(close).toHaveBeenCalledOnce()
    expect(useCopyStore.getState().operations[0]?.id).toBe('copy-2')
  })
})
